// Run manually with `npm run build-font` whenever the pinned font weights or
// the character set below change. Output is committed to api/_lib/font-data.js
// and required synchronously at runtime — no network fetch happens in the
// serverless functions themselves.
//
// The font is SUBSET to the characters the cards actually draw (Google Fonts'
// `text=` parameter does the subsetting server-side). The full Latin file was
// ~94 KB and was embedded in every card; the subset is a small fraction of
// that. Each weight is its own file, so both are embedded and declared with
// their real weights (the previous script embedded only the first file and
// declared it for 600 AND 700).
//
// Characters outside this set (e.g. a non-Latin display name) fall back to the
// system font in the card, which is the right trade for a per-request payload.

const fs = require('fs');
const path = require('path');

const ASCII = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('');
const EXTRA = '·–—…•°×→’‘“”éèêëáàâäíìîïóòôöúùûüñçßÉÈÁÍÓÚÑÇ';
const GLYPHS = ASCII + EXTRA;

const CSS_URL = `https://fonts.googleapis.com/css2?family=Chakra+Petch:wght@600;700&display=swap&text=${encodeURIComponent(GLYPHS)}`;
const OUT_PATH = path.join(__dirname, '..', 'api', '_lib', 'font-data.js');
const WARN_BYTES = 60 * 1024;

async function main() {
  const cssRes = await fetch(CSS_URL, { headers: { 'User-Agent': 'Mozilla/5.0' } });
  if (!cssRes.ok) throw new Error(`Failed to fetch font CSS: ${cssRes.status}`);
  const css = await cssRes.text();

  const blocks = css.match(/@font-face\s*\{[^}]+\}/g) || [];
  const faces = [];
  let totalBytes = 0;
  for (const block of blocks) {
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
    const url = block.match(/url\((https:\/\/fonts\.gstatic\.com[^)]+)\)/)?.[1];
    if (!weight || !url) continue;
    const fontRes = await fetch(url);
    if (!fontRes.ok) throw new Error(`Failed to fetch font file (${weight}): ${fontRes.status}`);
    const buf = Buffer.from(await fontRes.arrayBuffer());
    totalBytes += buf.length;
    faces.push(`@font-face{font-family:'Chakra Petch';font-weight:${weight};src:url(data:font/woff2;base64,${buf.toString('base64')}) format('woff2');}`);
    console.log(`  weight ${weight}: ${(buf.length / 1024).toFixed(1)} KB`);
  }
  if (!faces.length) throw new Error('No @font-face blocks with a gstatic URL found in the fetched CSS');
  if (totalBytes > WARN_BYTES) {
    console.warn(`WARNING: ${(totalBytes / 1024).toFixed(1)} KB embedded — larger than expected for a subset. Did the text= parameter get ignored?`);
  }

  const out = `// Generated by scripts/build-font.js - do not edit by hand.\n// Re-run that script and commit the new output if the pinned weights or glyph set change.\nmodule.exports = ${JSON.stringify(faces.join(''))};\n`;
  fs.writeFileSync(OUT_PATH, out);
  console.log(`Wrote ${OUT_PATH} (${faces.length} weight(s), ${(totalBytes / 1024).toFixed(1)} KB font data, ${(out.length / 1024).toFixed(1)} KB output file)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
